const BY_ID = new Map<string, readonly string[]>();
for (const group of GROUPS) {
  const selectable = group.filter((id) =>
    !FOOTBALL_BAR_TRIVIA_V2_RETIREMENTS.has(id) && !(id in FOOTBALL_BAR_TRIVIA_V2_REWRITES)
  );
  if (selectable.length < 2) continue;
  for (const id of selectable) {
    if (BY_ID.has(id)) throw new Error("Bar Trivia fact-family ID belongs to two clusters: " + id);
    BY_ID.set(id, selectable);
  }
}
export function footballTriviaFamilyMemberIds(id: string): readonly string[] {
  return BY_ID.get(id) ?? [id];
}
export function footballTriviaConceptKey(id: string): string {
  return footballTriviaFamilyMemberIds(id).join("|");
}
