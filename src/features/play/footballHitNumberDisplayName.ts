const footballAcronyms: Readonly<Record<string, string>> = {
  usc: "USC", lsu: "LSU", ucla: "UCLA", ucf: "UCF", byu: "BYU",
  smu: "SMU", tcu: "TCU", unc: "UNC", ut: "UT", nfl: "NFL", cfb: "CFB",
};

/** Presentation only. The original published board and recorded stats remain authoritative. */
export function footballHitNumberDisplayName(id: string, publishedName?: string): string {
  const season = /^nflverse-player-season-(00-\d{7})-(\d{4})$/.exec(id);
  if (season) {
    const name = nflverseQuarterbackNameBySourceId[season[1]!];
    return name ? `${name} · ${season[2]}` : `NFL QB · ${season[2]}`;
  }
  const sourceSeason = /^nflverse-player-season-.*-(\d{4})$/.exec(id);
  if (sourceSeason) return `NFL QB · ${sourceSeason[1]}`;
  const fallback = publishedName?.trim() || id.split("-").filter(Boolean)
    .map(part => part[0]!.toUpperCase() + part.slice(1)).join(" ");
  // Never expose a provider placeholder as if it were a player's real name.
  if (/^nflverse player season\b/i.test(fallback)) {
    const year = /\b(19|20)\d{2}\b/.exec(fallback)?.[0];
    return year ? `NFL QB · ${year}` : "NFL QB season";
  }
  return fallback.replace(/\b(usc|lsu|ucla|ucf|byu|smu|tcu|unc|ut|nfl|cfb)\b/gi, word =>
    footballAcronyms[word.toLowerCase()] ?? word,
  );
}
