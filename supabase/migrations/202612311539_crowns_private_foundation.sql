-- Keep the private catalog inaccessible to every account but the designated CROWNS owner.
do $$
declare t text;
begin
  foreach t in array array['crowns_subjects','crowns_series','crowns_templates','crowns_cards','crowns_variants','crowns_copies']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from public, anon, authenticated', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('drop policy if exists crowns_owner_only on public.%I', t);
    execute format('create policy crowns_owner_only on public.%I for all to authenticated using (public.crowns_is_owner()) with check (public.crowns_is_owner())', t);
  end loop;
end $$;

