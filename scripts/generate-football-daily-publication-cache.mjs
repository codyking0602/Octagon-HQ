import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = resolve(repoRoot, "supabase/functions/daily-challenge-runtime");
const CACHE_START_DAY = "2026-09-01";
const CACHE_END_DAY = "2028-12-31";
const SHARD_MAX_BYTES = 750_000;
const CACHE_MAX_BYTES = 18_000_000;

function dayStamp(day) {
  const stamp = Date.parse(`${day}T00:00:00.000Z`);
  if (!Number.isFinite(stamp)) throw new Error(`Invalid Football Daily cache day ${day}.`);
  return stamp;
}

function isoDay(stamp) {
  return new Date(stamp).toISOString().slice(0, 10);
}

function monthKey(day) {
  return day.slice(0, 7);
}

await mkdir(outDir, { recursive: true });
for (const name of await readdir(outDir)) {
  if (/^football-publication-\d{4}-\d{2}\.generated\.mjs$/.test(name)) {
    await rm(resolve(outDir, name), { force: true });
  }
}

const server = await createServer({
  root: repoRoot,
  configFile: false,
  logLevel: "error",
  server: { middlewareMode: true },
  appType: "custom",
});

const byMonth = new Map();
try {
  const runtime = await server.ssrLoadModule(
    "/src/features/play/footballTodayChallengePublicationRuntime.ts",
  );
  const build = runtime.buildFootballTodayPersistenceSetup;
  if (typeof build !== "function") {
    throw new Error("Football Daily publication source is missing buildFootballTodayPersistenceSetup.");
  }

  const start = dayStamp(CACHE_START_DAY);
  const end = dayStamp(CACHE_END_DAY);
  for (let stamp = start; stamp <= end; stamp += 86_400_000) {
    const day = isoDay(stamp);
    const publication = build(day);
    const serialized = JSON.stringify(publication);
    if (!serialized || serialized === "{}") {
      throw new Error(`Football Daily publication cache produced an empty setup for ${day}.`);
    }
    const month = monthKey(day);
    const entries = byMonth.get(month) ?? [];
    entries.push([day, serialized]);
    byMonth.set(month, entries);
  }
} finally {
  await server.close();
}

const monthKeys = [...byMonth.keys()].sort();
let totalBytes = 0;
for (const month of monthKeys) {
  const entries = byMonth.get(month);
  const serializedByDay = Object.fromEntries(entries);
  const moduleSource = `// Generated by scripts/generate-football-daily-publication-cache.mjs. Do not edit.
const publications = ${JSON.stringify(serializedByDay)};

export function buildFootballTodayPersistenceSetup(day) {
  const serialized = publications[day];
  if (typeof serialized !== "string") {
    throw new Error(\`Football Daily publication cache does not contain \${day}.\`);
  }
  return JSON.parse(serialized);
}
`;
  const bytes = Buffer.byteLength(moduleSource);
  if (bytes > SHARD_MAX_BYTES) {
    throw new Error(`Football Daily publication shard ${month} is ${bytes} bytes; expected <= ${SHARD_MAX_BYTES}.`);
  }
  totalBytes += bytes;
  await writeFile(
    resolve(outDir, `football-publication-${month}.generated.mjs`),
    moduleSource,
    "utf8",
  );
}

if (totalBytes > CACHE_MAX_BYTES) {
  throw new Error(`Football Daily publication cache is ${totalBytes} bytes; expected <= ${CACHE_MAX_BYTES}.`);
}

const loaderLines = monthKeys.map((month) => (
  `  "${month}": () => import("./football-publication-${month}.generated.mjs"),`
)).join("\n");

const registrySource = `// Generated by scripts/generate-football-daily-publication-cache.mjs. Do not edit.
const loaders = {
${loaderLines}
};

export const FOOTBALL_DAILY_PUBLICATION_CACHE_START = "${CACHE_START_DAY}";
export const FOOTBALL_DAILY_PUBLICATION_CACHE_END = "${CACHE_END_DAY}";

export async function buildFootballTodayPersistenceSetup(day) {
  if (typeof day !== "string" || !/^\\d{4}-\\d{2}-\\d{2}$/.test(day)) {
    throw new Error("Football Daily publication day must use YYYY-MM-DD.");
  }
  const loader = loaders[day.slice(0, 7)];
  if (loader) {
    const shard = await loader();
    return shard.buildFootballTodayPersistenceSetup(day);
  }

  // This path protects the product after the generated cache horizon instead of
  // creating a hidden expiration date. It is intentionally not used for normal
  // current-day materialization because the canonical fallback runtime is much heavier.
  const fallback = await import("./football-publication-fallback.generated.mjs");
  return fallback.buildFootballTodayPersistenceSetup(day);
}
`;

await writeFile(
  resolve(outDir, "football-publication.generated.mjs"),
  registrySource,
  "utf8",
);

console.log(
  `Generated Football Daily publication cache ${CACHE_START_DAY}..${CACHE_END_DAY} in ${monthKeys.length} monthly shards (${totalBytes} bytes).`,
);
