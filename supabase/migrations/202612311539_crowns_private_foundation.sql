-- CROWNS is owner-only until a separately approved public release.
-- Do not reuse the shared Picks owner privilege: it also includes test accounts.
create table if not exists public.crowns_owners (
  profile_id uuid primary key references public.profiles(id) on delete cascade
);
insert into public.crowns_owners(profile_id)
select id from public.profiles where normalized_name = 'CODY'
on conflict do nothing;

create table if not exists public.crowns_release (
  singleton boolean primary key default true check (singleton),
  public_enabled boolean not null default false,
  updated_at timestamptz not null default now()
);
insert into public.crowns_release(singleton, public_enabled)
values (true, false) on conflict (singleton) do nothing;

alter table public.crowns_owners enable row level security;
alter table public.crowns_release enable row level security;
revoke all on public.crowns_owners, public.crowns_release from public, anon, authenticated;

create or replace function public.crowns_is_owner()
returns boolean language sql stable security definer set search_path = ''
as $$
  select (select auth.uid()) is not null
    and exists (
      select 1 from public.crowns_owners o
      where o.profile_id = (select auth.uid())
    );
$$;

create or replace function public.crowns_is_public()
returns boolean language sql stable security definer set search_path = ''
as $$
  select coalesce((select r.public_enabled from public.crowns_release r where r.singleton), false);
$$;

create or replace function public.crowns_can_view()
returns boolean language sql stable security definer set search_path = ''
as $$
  select public.crowns_is_owner() or public.crowns_is_public();
$$;

create or replace function public.crowns_access()
returns jsonb language sql stable security definer set search_path = ''
as $$
  select jsonb_build_object(
    'is_owner', public.crowns_is_owner(),
    'is_public', public.crowns_is_public(),
    'can_view', public.crowns_can_view()
  );
$$;
revoke all on function public.crowns_is_owner() from public, anon, authenticated;
revoke all on function public.crowns_is_public() from public, anon, authenticated;
revoke all on function public.crowns_can_view() from public, anon, authenticated;
revoke all on function public.crowns_access() from public, anon, authenticated;
grant execute on function public.crowns_is_owner() to anon, authenticated;
grant execute on function public.crowns_is_public() to anon, authenticated;
grant execute on function public.crowns_can_view() to anon, authenticated;
grant execute on function public.crowns_access() to anon, authenticated;

create table if not exists public.crowns_subjects (
  id bigint generated by default as identity primary key,
  name text not null unique check (length(trim(name)) between 1 and 160),
  subject_kind text not null default 'person'
    check (subject_kind in ('person','athlete','character','event','group','other')),
  sport text,
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.crowns_series (
  slug text primary key check (slug ~ '^[a-z0-9-]+$'),
  name text not null,
  family text not null check (family in ('classic','eclipse','nova','independent')),
  series_kind text not null check (series_kind in ('base','insert','collection')),
  rarity text not null default 'standard'
    check (rarity in ('standard','signature','premium','ultra-rare')),
  orientation text not null default 'portrait' check (orientation in ('portrait','landscape')),
  description text not null default '',
  sort_order integer not null default 100,
  accent text,
  active boolean not null default true
);

create table if not exists public.crowns_templates (
  id bigint generated by default as identity primary key,
  name text not null,
  series_slug text references public.crowns_series(slug) on delete set null,
  canva_reference text,
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.crowns_cards (
  id bigint generated by default as identity primary key,
  subject_id bigint not null references public.crowns_subjects(id),
  series_slug text references public.crowns_series(slug) on delete set null,
  template_id bigint references public.crowns_templates(id) on delete set null,
  source_sheet text,
  source_row integer unique,
  classification text,
  requested_by text,
  legacy_design_code text,
  title text,
  status text not null default 'planned'
    check (status in ('planned','designing','finished','printed')),
  front_path text,
  back_path text,
  orientation_override text check (orientation_override in ('portrait','landscape')),
  is_published boolean not null default false,
  legacy boolean not null default false,
  legacy_reason text,
  intended_print_qty integer not null default 0 check (intended_print_qty >= 0),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists crowns_cards_subject_idx on public.crowns_cards(subject_id);
create index if not exists crowns_cards_series_idx on public.crowns_cards(series_slug);
create index if not exists crowns_cards_status_idx on public.crowns_cards(status);
create unique index if not exists crowns_one_the_only_checklist
  on public.crowns_cards(subject_id) where series_slug = 'the-one-the-only';

create or replace function public.crowns_enforce_closed_checklist()
returns trigger language plpgsql set search_path = ''
as $crowns_closed_checklist$
declare v_name text;
begin
  if new.series_slug = 'the-one-the-only' then
    select s.name into v_name from public.crowns_subjects s where s.id = new.subject_id;
    if v_name not in ('Conor McGregor','Jon Jones') or v_name is null then
      raise exception 'THE ONE, THE ONLY is limited to Conor McGregor and Jon Jones';
    end if;
  end if;
  return new;
end;
$crowns_closed_checklist$;
drop trigger if exists crowns_closed_checklist on public.crowns_cards;
create trigger crowns_closed_checklist before insert or update of series_slug,subject_id
on public.crowns_cards for each row execute function public.crowns_enforce_closed_checklist();

create table if not exists public.crowns_variants (
  id bigint generated by default as identity primary key,
  card_id bigint not null references public.crowns_cards(id) on delete cascade,
  name text not null,
  variant_kind text not null default 'parallel' check (variant_kind in ('parallel','special')),
  border_treatment text,
  pattern_treatment text,
  team_color_match boolean not null default false,
  jersey_number_match boolean not null default false,
  serial_limit integer check (serial_limit between 1 and 100000),
  signature_one_of_one boolean not null default false,
  legacy boolean not null default false,
  front_path text,
  back_path text,
  status text not null default 'planned'
    check (status in ('planned','designing','finished','printed')),
  notes text,
  created_at timestamptz not null default now(),
  constraint crowns_one_of_one check (not signature_one_of_one or serial_limit = 1)
);
create index if not exists crowns_variants_card_idx on public.crowns_variants(card_id);

create table if not exists public.crowns_copies (
  id bigint generated by default as identity primary key,
  card_id bigint not null references public.crowns_cards(id) on delete cascade,
  variant_id bigint references public.crowns_variants(id) on delete cascade,
  serial_number integer check (serial_number > 0),
  status text not null default 'planned'
    check (status in ('planned','ordered','printed','in-hand')),
  notes text,
  created_at timestamptz not null default now()
);
create index if not exists crowns_copies_card_idx on public.crowns_copies(card_id);

